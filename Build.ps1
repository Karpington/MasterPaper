# Native Windows build; compatible with Windows PowerShell 5.1 and PowerShell 7.
[CmdletBinding()]
param(
    [ValidateSet('build','rebuild','clean','view','watch','bibpreview','figpreview','tabpreview','package','help')]
    [string]$Task = 'build',
    [string]$TemplatePath,
    [string]$OutputDir,
    [string]$OutputFile,
    [string]$InputFile
)
$ErrorActionPreference = 'Stop'
$projectRoot = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Setting([string]$Name) {
    $text = [IO.File]::ReadAllText((Join-Path $projectRoot 'Makefile'))
    $match = [regex]::Match($text, '(?m)^' + $Name + '\s*[:?]?=\s*([^\r\n#]+)')
    if (-not $match.Success) { throw "Missing Makefile setting: $Name" }
    return $match.Groups[1].Value.Trim()
}
function Project-Path([string]$Relative) {
    $full = [IO.Path]::GetFullPath((Join-Path $projectRoot $Relative))
    if (-not $full.StartsWith($projectRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Path must be inside the project: $Relative"
    }
    return $full
}
function Remove-Generated([string]$Path) {
    $checked = Project-Path $Path
    if (Test-Path -LiteralPath $checked) {
        $item = Get-Item -LiteralPath $checked -Force
        if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Refusing to remove a link: $checked" }
        if (-not (Test-Path -LiteralPath (Join-Path $checked '.windows-build-generated'))) {
            throw "Not a Windows-generated build directory: $checked. Rename it before continuing."
        }
        # Resolve and verify the absolute target before recursive removal.
        $resolved = (Resolve-Path -LiteralPath $checked).Path
        if ($resolved -ne $checked) { throw "Unexpected resolved path: $resolved" }
        Remove-Item -LiteralPath $checked -Recurse -Force
    }
}
function Ensure-Generated([string]$Path) {
    $checked = Project-Path $Path
    if (Test-Path -LiteralPath $checked) {
        if ((Get-Item -LiteralPath $checked -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
            throw "Rename the existing link before using the Windows build: $checked"
        }
        if (-not (Test-Path -LiteralPath (Join-Path $checked '.windows-build-generated'))) {
            if (@(Get-ChildItem -LiteralPath $checked -Force).Count -gt 0) {
                throw "Rename the existing directory before using the Windows build: $checked"
            }
            [IO.File]::WriteAllText((Join-Path $checked '.windows-build-generated'), 'Generated by Build.ps1', $utf8)
        }
    } else {
        New-Item -ItemType Directory -Path $checked | Out-Null
        [IO.File]::WriteAllText((Join-Path $checked '.windows-build-generated'), 'Generated by Build.ps1', $utf8)
    }
}
function Run-Tool([string]$Name, [string[]]$Arguments, [string]$LogName) {
    $command = Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $command) { throw "Required tool missing: $Name. Install MiKTeX or TeX Live and add its bin directory to PATH." }
    Write-Host "Running $Name..."
    $log = Join-Path $buildPath $LogName
    # Windows PowerShell treats native stderr as errors; use the exit code instead.
    $savedPreference = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    & $command.Source @Arguments > $log 2>&1
    $code = $LASTEXITCODE
    $ErrorActionPreference = $savedPreference
    if ($code -ne 0) {
        Get-Content -LiteralPath $log -Tail 45 | Write-Host
        throw "$Name failed (exit $code). Full output: $log"
    }
}
function Prepare-Template {
    $source = Project-Path $TemplatePath
    if (-not (Test-Path -LiteralPath (Join-Path $source 'main.tex'))) { throw "Template not found: $source" }
    $downloadMakefile = Join-Path $source 'Makefile'
    if (Test-Path -LiteralPath $downloadMakefile) {
        $settings = [IO.File]::ReadAllText($downloadMakefile)
        $url = [regex]::Match($settings, '(?m)^\w*TEMPLATE_URL\s*:=\s*(https://\S+)').Groups[1].Value
        $folder = [regex]::Match($settings, '(?m)^\w*TEMPLATE_EXTRACT_DIR\s*:=\s*\$\(OUTPUT_DIR\)/([^\s/]+)').Groups[1].Value
        if (-not $url -or -not $folder) { throw "Unsupported template download settings: $downloadMakefile" }
        $downloadPath = Project-Path 'download'
        if (-not (Test-Path -LiteralPath (Join-Path $downloadPath $folder))) {
            New-Item -ItemType Directory -Path $downloadPath -Force | Out-Null
            $archive = Join-Path $downloadPath ([IO.Path]::GetFileName(([uri]$url).AbsolutePath))
            Write-Host "Downloading publisher template: $url"
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
            Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $archive
            Expand-Archive -LiteralPath $archive -DestinationPath $downloadPath -Force
            if (-not (Test-Path -LiteralPath (Join-Path $downloadPath $folder))) { throw 'Unexpected publisher archive structure.' }
        }
    }
    Remove-Generated 'template'
    Ensure-Generated 'template'
    Get-ChildItem -LiteralPath $source -Force | Copy-Item -Destination (Join-Path $projectRoot 'template') -Recurse -Force
    Ensure-Generated $OutputDir
    $inkscape = Get-Command inkscape.com -ErrorAction SilentlyContinue
    if ($inkscape) { $env:PATH = (Split-Path $inkscape.Source) + ';' + $env:PATH }
    elseif (Test-Path -LiteralPath "$env:ProgramFiles\Inkscape\bin\inkscape.exe") {
        $env:PATH = "$env:ProgramFiles\Inkscape\bin;" + $env:PATH
    }
    if (-not (Get-Command inkscape.exe -ErrorAction SilentlyContinue)) {
        throw 'Inkscape is required for the SVG examples. Install the Windows version and add its bin directory to PATH.'
    }
}
function Compile-Paper([string]$Source, [string]$Job) {
    $argsTex = @('-shell-escape','-interaction=nonstopmode','-halt-on-error','-file-line-error',"-output-directory=$OutputDir","-jobname=$Job",$Source)
    Run-Tool 'pdflatex' $argsTex "$Job-pass1.txt"
    $aux = Join-Path $buildPath "$Job.aux"
    if ((Test-Path -LiteralPath $aux) -and ([IO.File]::ReadAllText($aux) -match '\\bibdata\{') -and ([IO.File]::ReadAllText($aux) -match '\\citation\{')) {
        Run-Tool 'bibtex' @("$OutputDir/$Job") "$Job-bibtex.txt"
    }
    Push-Location $buildPath
    try {
        foreach ($index in @(@('acn','acr','alg',"$Job.ist"), @('glo','gls','glg',"$Job.ist"), @('nlo','nls','nlg','nomencl.ist'))) {
            $inputIndex = "$Job.$($index[0])"
            if ((Test-Path -LiteralPath $inputIndex) -and (Get-Item -LiteralPath $inputIndex).Length -gt 0) {
                Run-Tool 'makeindex' @('-s',$index[3],'-t',"$Job.$($index[2])",'-o',"$Job.$($index[1])",$inputIndex) "$Job-$($index[0])-index.txt"
            }
        }
    } finally { Pop-Location }
    Run-Tool 'pdflatex' $argsTex "$Job-pass2.txt"
    Run-Tool 'pdflatex' $argsTex "$Job-pass3.txt"
    $finalLog = Join-Path $buildPath "$Job.log"
    if (Select-String -LiteralPath $finalLog -Pattern 'There were undefined references|There were undefined citations' -Quiet) {
        Write-Warning "Unresolved references or citations remain; see $finalLog"
    }
    Write-Host "PDF ready: $(Join-Path $buildPath "$Job.pdf")"
}
function Source-Stamp {
    $items = foreach ($entry in @('main.tex','Makefile','Build.ps1','common','secs','lists','codes','tabs','figs','imgs',$TemplatePath)) {
        Get-ChildItem -LiteralPath (Join-Path $projectRoot $entry) -File -Recurse -ErrorAction SilentlyContinue
    }
    return (($items | Sort-Object FullName | ForEach-Object { "$($_.FullName):$($_.Length):$($_.LastWriteTimeUtc.Ticks)" }) -join '|')
}

Push-Location $projectRoot
try {
    if (-not $TemplatePath) { $TemplatePath = Read-Setting 'TEMPLATE_PATH' }
    if (-not $OutputDir) { $OutputDir = Read-Setting 'OUTPUT_DIR' }
    if (-not $OutputFile) { $OutputFile = Read-Setting 'OUTPUT_FILE' }
    if ($OutputFile -notmatch '^[A-Za-z0-9_-]+$') { throw 'OUTPUT_FILE must contain only letters, digits, underscores or hyphens.' }
    $buildPath = Project-Path $OutputDir
    # Only dedicated output folders can be cleaned; never source directories.
    if ($OutputDir -ne 'build') { throw 'OUTPUT_DIR must be build (also used by common/packages.tex for SVG exports).' }
    if ($Task -eq 'help') {
        Write-Host 'make -B | make rebuild | make view | make clean | make watch | make bibpreview | make package'
        Write-Host 'make figpreview INPUT_FILE=figs/PDFTexFigure.svg'
        Write-Host 'make tabpreview INPUT_FILE=tabs/stripify_table.tex'
        Write-Host 'Without make: powershell -NoProfile -ExecutionPolicy Bypass -File .\Build.ps1'
        return
    }
    if ($Task -in @('clean','rebuild')) {
        Remove-Generated $OutputDir
        Remove-Generated 'template'
        if ($Task -eq 'clean') { return }
    }
    Prepare-Template
    $source = Read-Setting 'MAIN_FILE_TEX'
    $job = $OutputFile
    if ($Task -eq 'bibpreview') { $source = 'template/BibPreview.tex'; $job = 'BibPreview' }
    if ($Task -in @('figpreview','tabpreview')) {
        if (-not $InputFile) { throw 'Specify INPUT_FILE (make) or -InputFile (Build.ps1).' }
        $kind = if ($Task -eq 'figpreview') { 'figs' } else { 'tabs' }
        $preview = if ($Task -eq 'figpreview') { 'FigPreview' } else { 'TabPreview' }
        $file = Get-Item -LiteralPath (Project-Path $InputFile)
        if ($file.DirectoryName -ne (Project-Path $kind)) { throw "Input must be directly in $kind/." }
        if ($file.BaseName -notmatch '^[A-Za-z0-9_-]+$') { throw 'Use letters, digits, underscores or hyphens in preview filenames.' }
        $job = $preview + '-' + $file.BaseName
        $source = "$OutputDir/$job.tex"
        $text = [IO.File]::ReadAllText((Join-Path $projectRoot "template/$preview.tex")).Replace('__BASE_NAME__', $file.BaseName)
        [IO.File]::WriteAllText((Join-Path $projectRoot $source), $text, $utf8)
    }
    $stamp = Source-Stamp
    Compile-Paper $source $job
    if ($Task -in @('view','watch')) { Start-Process -FilePath (Join-Path $buildPath "$job.pdf") }
    if ($Task -eq 'watch') {
        Write-Host 'Watching source files. Press Ctrl+C to stop.'
        while ($true) {
            Start-Sleep -Seconds 2
            $next = Source-Stamp
            if ($next -ne $stamp) {
                $stamp = $next
                try { Prepare-Template; Compile-Paper $source $job } catch { Write-Warning $_ }
            }
        }
    }
    if ($Task -eq 'package') {
        $package = Join-Path $buildPath 'package'
        Remove-Generated "$OutputDir/package"
        Ensure-Generated "$OutputDir/package"
        foreach ($entry in @('main.tex','Makefile','Build.ps1','README.md','LICENSE','common','secs','lists','codes','tabs','figs','imgs','templates','download')) {
            $path = Join-Path $projectRoot $entry
            if (Test-Path -LiteralPath $path) { Copy-Item -LiteralPath $path -Destination $package -Recurse -Force }
        }
        Compress-Archive -Path (Join-Path $package '*') -DestinationPath (Join-Path $buildPath 'package.zip') -Force
        Write-Host "Source archive ready: $(Join-Path $buildPath 'package.zip')"
    }
} catch {
    Write-Error $_ -ErrorAction Continue
    exit 1
} finally { Pop-Location }
